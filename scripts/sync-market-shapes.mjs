// Generate amplify/functions/market-shared/market.generated.ts from
// schema/market/ (the source of truth). The Lambdas are bundled without the
// schema folder, so they carry this copy; tests/market/validate.test.js fails
// when it drifts. Run: node scripts/sync-market-shapes.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const src = path.resolve(here, "../schema/market");
let out = "// GENERATED by scripts/sync-market-shapes.mjs from schema/market/. Do not edit.\n";
out += `export const SHAPES = ${JSON.stringify(fs.readFileSync(path.join(src, "market.shapes.ttl"), "utf8"))};\n`;
const dest = path.resolve(here, "../amplify/functions/market-shared/market.generated.ts");
fs.writeFileSync(dest, out);
console.log(`  wrote ${path.relative(process.cwd(), dest)}`);
