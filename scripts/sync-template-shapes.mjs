// Generate amplify/functions/templates-shared/templates.generated.ts from
// schema/ (the source of truth): the template shapes, the dhc-core T-Box (its
// dhc:NormEdition chain decides which norm shapes an edition runs) and every
// norm shapes file under schema/cbox/, keyed by the path dhc:shapesFile names.
// The Lambdas are bundled without the schema folder, so they carry this copy;
// tests/templates/templates.test.js fails when it drifts.
// Run: node scripts/sync-template-shapes.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const schema = path.resolve(here, "../schema");
const read = (rel) => fs.readFileSync(path.join(schema, rel), "utf8");
const walk = (dir) => fs.readdirSync(path.join(schema, dir), { withFileTypes: true }).flatMap((e) =>
  e.isDirectory() ? walk(`${dir}/${e.name}`) : e.name.endsWith(".shapes.ttl") ? [`${dir}/${e.name}`] : []);

const norms = Object.fromEntries(walk("cbox").sort().map((rel) => [rel, read(rel)]));
let out = "// GENERATED by scripts/sync-template-shapes.mjs from schema/. Do not edit.\n";
out += `export const TEMPLATE_SHAPES = ${JSON.stringify(read("templates/templates.shapes.ttl"))};\n`;
out += `export const TBOX = ${JSON.stringify(read("tbox/dhc-core.ttl"))};\n`;
out += `export const NORM_SHAPES: Record<string, string> = ${JSON.stringify(norms)};\n`;
const dest = path.resolve(here, "../amplify/functions/templates-shared/templates.generated.ts");
fs.writeFileSync(dest, out);
console.log(`  wrote ${path.relative(process.cwd(), dest)} (${Object.keys(norms).length} norm shapes files)`);
